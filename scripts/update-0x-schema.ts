// Refreshes the vendored subset of 0x's OpenAPI spec and the types and
// validators generated from it.
//
// The source is the spec in 0x's docs repository, which docs.0x.org publishes
// as https://docs.0x.org/openapi/evm-apis.json. The published copy is a
// re-rendered OpenAPI 3.1 file that drops the `enum: [true]`/`enum: [false]`
// that tell the `liquidityAvailable` variants apart, and turns nullable
// numeric strings such as `tokenMetadata.*.buyTaxBps` into empty object
// schemas; validators built from it either reject every real response or
// accept anything with `liquidityAvailable` and `zid`.
import { $ } from "bun"
import openapiTS, { astToString } from "openapi-typescript"
import path from "path"

const REPOSITORY = "0xProject/0x-docs"
const SPEC_PATH = "fern/openapi.json"
const OPERATIONS = [
  "/swap/allowance-holder/price",
  "/swap/allowance-holder/quote",
] as const

const root = path.join(import.meta.dir, "..")
const outputDirectory = path.join(root, "background/lib/validate/0x")
const specOutput = path.join(outputDirectory, "openapi.json")
const typesOutput = path.join(outputDirectory, "openapi.d.ts")

async function fetchJSON<T>(url: string): Promise<T> {
  const response = await fetch(url)
  if (!response.ok) {
    throw new Error(`${url} returned HTTP ${response.status}`)
  }
  return response.json()
}

const [latestCommit] = await fetchJSON<
  { sha: string; commit: { committer: { date: string } } }[]
>(
  `https://api.github.com/repos/${REPOSITORY}/commits?path=${SPEC_PATH}&per_page=1`,
)

const sourceURL = `https://raw.githubusercontent.com/${REPOSITORY}/${latestCommit.sha}/${SPEC_PATH}`
const spec = await fetchJSON<{
  openapi: string
  info: unknown
  paths: Record<
    string,
    { get: { parameters: unknown; responses: Record<string, unknown> } }
  >
}>(sourceURL)

// Only the success responses are kept: the error responses refer to shared
// components Taho doesn't read.
const vendored = {
  openapi: spec.openapi,
  info: spec.info,
  "x-taho-source": {
    url: sourceURL,
    committedAt: latestCommit.commit.committer.date,
    fetchedAt: new Date().toISOString().slice(0, 10),
  },
  paths: Object.fromEntries(
    OPERATIONS.map((operation) => {
      const { get } = spec.paths[operation]
      return [
        operation,
        { get: { ...get, responses: { 200: get.responses["200"] } } },
      ]
    }),
  ),
}

if (JSON.stringify(vendored).includes('"$ref"')) {
  throw new Error(
    "The vendored operations now use $ref; vendor the components.",
  )
}

await Bun.write(specOutput, `${JSON.stringify(vendored, null, 2)}\n`)

// The spec writes numeric strings as `allOf: [{}, numericString]` and
// optional enums as `anyOf: [{ not: {} }, enum]`; openapi-typescript renders
// the vacuous members as `unknown`.
function withoutVacuousMembers(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map(withoutVacuousMembers)
  }
  if (typeof value !== "object" || value === null) {
    return value
  }

  const schema = Object.fromEntries(
    Object.entries(value).map(([key, member]) => [
      key,
      withoutVacuousMembers(member),
    ]),
  )

  const vacuousMember = { allOf: "{}", anyOf: '{"not":{}}' } as const
  for (const combinator of ["allOf", "anyOf"] as const) {
    const members = schema[combinator]
    if (Array.isArray(members)) {
      const constraints = members.filter(
        (member) => JSON.stringify(member) !== vacuousMember[combinator],
      )
      if (constraints.length === 1) {
        delete schema[combinator]
        return { ...schema, ...constraints[0] }
      }
    }
  }

  return schema
}

const types = astToString(
  await openapiTS(JSON.stringify(withoutVacuousMembers(vendored))),
)
await Bun.write(
  typesOutput,
  `// Generated by scripts/update-0x-schema.ts from ./openapi.json. Do not edit.\n\n${types}`,
)

await $`bun run generate:validators`.cwd(root)
await $`bun fmt background/lib/validate`.cwd(root)

process.stdout.write(
  `Vendored ${REPOSITORY}@${latestCommit.sha.slice(0, 7)} (${latestCommit.commit.committer.date}).\n`,
)
